# letters = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i']

# უარყოფითი ინდექსებისა და slicing-ის გამოყენებით:

# 1. მიიღე ბოლო ელემენტი.
# 2. მიიღე ბოლო 5 ელემენტი.
# 3. მიიღე ყველაფერი ბოლო 3 ელემენტის გარდა.
# 4. მიიღე ['c', 'd', 'e'].
# 5. შემოატრიალე სია უკუღმა.

letters = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i']
print(letters[-1:])
print(letters[-5:])
print(letters[:-3])
print(letters[-7:-4])
print(letters[::-1])

# fruits = ["apple", "banana", "cherry", "orange", "mango", "grape", "kiwi"]

# Slicing-ის გამოყენებით:

# 1. აიღე პირველი 3 ელემენტი.
# 2. აიღე ბოლო 2 ელემენტი.
# 3. აიღე ელემენტები 1-ე ინდექსიდან 4-ე ინდექსამდე.
